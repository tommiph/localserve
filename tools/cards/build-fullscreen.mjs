/** Build self-contained design stylesheets from shared geometry and local motifs.
 * Keeping CSS within each declared package also supports native phone policies. */
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

export async function buildFullscreenStyles(root,{check=false}={}) {
  const common=await fs.readFile(path.join(root,'assets/card-fullscreen.css'),'utf8');
  let count=0;
  for(const folder of await fs.readdir(path.join(root,'plugins'),{withFileTypes:true})) {
    if(!folder.isDirectory())continue;
    const file=path.join(root,'plugins',folder.name,'declaration.json');
    let plugin;try {plugin=JSON.parse(await fs.readFile(file,'utf8'));} catch(error){if(error.code==='ENOENT')continue;throw error;}
    for(const design of plugin.cardTemplates||[]) {
      // Only dedicated full-screen documents use the shared geometry bundle.
      // Responsive designs keep their own card.css at every display size.
      if(!design.id.endsWith('-fullscreen')||design.entry!=='fullscreen.html')continue;
      if(!/^cards\/[a-z0-9-]+$/.test(design.directory))throw Error('Invalid design directory.');
      const directory=path.join(root,'plugins',folder.name,design.directory);
      const motif=await fs.readFile(path.join(directory,'fullscreen-theme.css'),'utf8');
      const expected='/* Generated by tools/cards/build-fullscreen.mjs from shared geometry and fullscreen-theme.css. */\n'+common+'\n'+motif;
      const target=path.join(directory,'fullscreen.css');
      if(check){if(await fs.readFile(target,'utf8')!==expected)throw Error('Rebuild full-screen stylesheet: '+folder.name);}
      else await fs.writeFile(target,expected);
      count++;
    }
  }
  return count;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify({designs:await buildFullscreenStyles(fileURLToPath(new URL('../../',import.meta.url)),{check:process.argv.includes('--check')})}));
}
